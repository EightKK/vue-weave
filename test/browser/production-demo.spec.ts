import { dragBy, expect, pageErrors, test } from './support'

test('production demo edits the schedule, graph and load from the homepage', async ({ page }) => {
  const errors = pageErrors(page)
  await page.goto('/')
  await page.getByRole('button', { name: '日本語' }).click()
  await expect(page.getByRole('heading', { name: '製造計画', exact: true })).toBeVisible()
  await page.getByRole('button', { name: /切断Aを予備機へ/ }).click()
  await expect(page.getByRole('row', { name: /出荷できる時刻/ })).toContainText('19:00')

  const gantt = page.getByRole('region', { name: 'ガントチャート' })
  const cut = gantt.getByRole('button', { name: '切断B 13:00–15:00' })
  await dragBy(page, cut, 42, 0)
  await expect(gantt.getByRole('button', { name: '検査 16:00–18:00' })).toBeVisible()
  await expect(page.getByLabel('工程図', { exact: true }).getByLabel('検査 16:00–18:00')).toBeVisible()
  await expect(page.getByRole('region', { name: '設備負荷' }).getByRole('button', { name: /CNC設備 14:00.16:00/ })).toBeVisible()
  await expect(page.getByRole('row', { name: /出荷できる時刻/ })).toContainText('20:00')

  await page.getByRole('button', { name: 'この案を採用' }).click()
  await expect(page.getByRole('status').filter({ hasText: '変更案を採用しました。' })).toBeVisible()
  await page.getByRole('button', { name: '採用を取り消す' }).click()
  await expect(page.getByRole('row', { name: /出荷できる時刻/ })).toContainText('17:00')
  expect(errors).toEqual([])
})

test('lot flow keeps the same network as the displayed unit and language change', async ({ page }) => {
  const errors = pageErrors(page)
  await page.goto('/')
  await page.getByRole('button', { name: '日本語' }).click()
  await page.getByRole('button', { name: 'ロットの流れ' }).click()
  await expect(page.getByRole('heading', { name: 'ロットの流れ' })).toBeVisible()

  await page.locator('.production-table').getByRole('button', { name: 'ラインB' }).click()
  await expect(page.locator('.production-content[aria-live]')).toContainText('-4個')
  await page.getByRole('button', { name: '原価 (EUR)' }).click()
  await expect(page.locator('.production-content[aria-live]')).toContainText('-100 €')
  await expect(page.locator('.vw-network-edge.vw-is-animated')).toHaveCount(1)
  await page.getByRole('button', { name: 'English' }).click()
  await expect(page.getByRole('heading', { name: 'Lot flow' })).toBeVisible()
  await expect(page.locator('.production-content[aria-live]')).toContainText('Line B')
  await page.getByRole('button', { name: 'View code' }).click()
  await expect(page.locator('pre')).toContainText('layoutFlowGraph')
  await page.getByRole('link', { name: 'Examples' }).click()
  await expect(page).toHaveURL(/gallery\.html$/)
  await expect(page.getByRole('button', { name: 'Quantity flow', exact: true })).toBeVisible()
  expect(errors).toEqual([])
})
