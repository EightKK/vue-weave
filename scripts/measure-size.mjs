// Measures what the built package costs a consumer. Run it after `npm run build`.
//
//   npm run size                  print the table and write artifacts/size/size.json
//   npm run size -- --update      also rewrite size-baseline.json from this run
//   npm run size:check            compare this run with size-baseline.json and fail past the tolerance
//
// Two kinds of numbers: the published files themselves (dist/index.js, dist/core.js, the shared chunk and
// dist/style.css) and the tree-shaken cost of importing one thing. For the second, a one-line consumer is bundled with
// Vite (Vue external, minified) and the output is measured, so the figure is what a bundler keeps for that import.
// Sizes are raw, gzip (level 9) and brotli (quality 11) bytes. They depend on the bundler and minifier version, so the
// baseline is meant for one pinned toolchain (the lockfile) and is not wired into `check` or CI.
import { brotliCompressSync, constants, gzipSync } from 'node:zlib'
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

export const root = fileURLToPath(new URL('../', import.meta.url))
export const baselinePath = join(root, 'size-baseline.json')
export const outputPath = join(root, 'artifacts', 'size', 'size.json')
export const defaultTolerance = 0.05
// Differences smaller than this many bytes never fail, so a tiny entry does not trip the percentage on a few bytes.
export const absoluteSlack = 64

// Representative core functions, measured when the built core entry exports them.
export const coreSamples = ['scheduleTasks', 'levelResources', 'layoutLayeredGraph', 'routeGraphEdges', 'toMsProjectXml', 'renderTimelineSvg', 'flattenTreeGrid']

export function measureBytes(input) {
  const buffer = typeof input === 'string' ? Buffer.from(input) : input
  return {
    raw: buffer.length,
    gzip: gzipSync(buffer, { level: 9 }).length,
    brotli: brotliCompressSync(buffer, { params: { [constants.BROTLI_PARAM_QUALITY]: 11 } }).length,
  }
}

export function sumSizes(list) {
  return list.reduce((total, size) => ({ raw: total.raw + size.raw, gzip: total.gzip + size.gzip, brotli: total.brotli + size.brotli }), { raw: 0, gzip: 0, brotli: 0 })
}

export function formatBytes(bytes) {
  if (bytes < 1024) return `${bytes} B`
  return `${(bytes / 1024).toFixed(bytes < 10 * 1024 ? 2 : 1)} kB`
}

/** Splits the value exports of the built Vue entry into components (PascalCase) and composables (useXxx), leaving out everything core also exports. */
export function classifyExports(entryNames, coreNames) {
  const core = new Set(coreNames)
  const own = entryNames.filter(name => !core.has(name) && name !== 'default')
  return {
    components: own.filter(name => /^[A-Z]/.test(name)).sort(),
    composables: own.filter(name => /^use[A-Z]/.test(name)).sort(),
  }
}

/** One row of the report per measured item, in a stable order: { name, group, raw, gzip, brotli }. */
export function toRows(sections) {
  return sections.flatMap(({ group, items }) => items.map(item => ({ group, ...item })))
}

export function renderTable(rows) {
  const lines = ['| Item | Group | Raw | Gzip | Brotli |', '| --- | --- | ---: | ---: | ---: |']
  for (const row of rows) lines.push(`| ${row.name} | ${row.group} | ${formatBytes(row.raw)} | ${formatBytes(row.gzip)} | ${formatBytes(row.brotli)} |`)
  return lines.join('\n')
}

/** The baseline file holds only the gzip and raw figures of each item, keyed by "group/name". */
export function toBaseline(rows, tolerance = defaultTolerance) {
  const sizes = {}
  for (const row of rows) sizes[`${row.group}/${row.name}`] = { raw: row.raw, gzip: row.gzip }
  return { note: 'Generated by `npm run size -- --update`. Compared by `npm run size:check`.', tolerance, sizes }
}

/**
 * Compares measured rows with a baseline. An item fails when its gzip size grew by more than the tolerance (and more
 * than absoluteSlack bytes). Items missing from the baseline or from the build are reported as problems too, since the
 * baseline no longer describes the package. Shrinking never fails, but is listed so the baseline can be refreshed.
 */
export function compareToBaseline(rows, baseline, tolerance = baseline.tolerance ?? defaultTolerance) {
  const problems = []
  const notes = []
  const seen = new Set()
  for (const row of rows) {
    const key = `${row.group}/${row.name}`
    seen.add(key)
    const before = baseline.sizes[key]
    if (!before) { problems.push(`${key} is not in the baseline`); continue }
    const grew = row.gzip - before.gzip
    if (grew > absoluteSlack && grew > before.gzip * tolerance) {
      problems.push(`${key} grew from ${before.gzip} to ${row.gzip} gzip bytes (+${((grew / before.gzip) * 100).toFixed(1)}%, limit ${(tolerance * 100).toFixed(0)}%)`)
    } else if (-grew > absoluteSlack && -grew > before.gzip * tolerance) {
      notes.push(`${key} shrank from ${before.gzip} to ${row.gzip} gzip bytes`)
    }
  }
  for (const key of Object.keys(baseline.sizes)) if (!seen.has(key)) problems.push(`${key} is in the baseline but was not measured`)
  return { ok: problems.length === 0, problems, notes }
}

async function measurePublishedFiles() {
  const dist = join(root, 'dist')
  const files = readdirSync(dist).filter(name => /\.(?:js|css)$/.test(name)).sort()
  const items = files.map(name => ({ name: `dist/${name.replace(/-[\w-]{8}\.js$/, '-[hash].js')}`, ...measureBytes(readFileSync(join(dist, name))) }))
  items.push({ name: 'dist total (js + css)', ...sumSizes(items) })
  return items
}

async function bundleConsumer(vite, source) {
  const distIndex = join(root, 'dist', 'index.js')
  const distCore = join(root, 'dist', 'core.js')
  const id = '\0size-entry'
  const result = await vite.build({
    configFile: false,
    logLevel: 'silent',
    root,
    plugins: [{
      name: 'size-entry',
      resolveId(request) {
        if (request === id) return id
        if (request === 'vue-weave') return distIndex
        if (request === 'vue-weave/core') return distCore
        return null
      },
      load(request) { return request === id ? source : null },
    }],
    build: {
      write: false,
      minify: true,
      target: 'es2022',
      reportCompressedSize: false,
      rollupOptions: { input: id, external: ['vue'], output: { format: 'es' } },
    },
  })
  const outputs = (Array.isArray(result) ? result : [result]).flatMap(entry => entry.output)
  return sumSizes(outputs.filter(file => file.type === 'chunk').map(file => measureBytes(file.code)))
}

export async function measureAll() {
  const vue = await import(pathToFileURL(join(root, 'dist', 'index.js')).href)
  const core = await import(pathToFileURL(join(root, 'dist', 'core.js')).href)
  const vite = await import('vite')
  const { components, composables } = classifyExports(Object.keys(vue), Object.keys(core))
  const consumer = async (module, name) => ({ name, ...(await bundleConsumer(vite, `import { ${name} } from '${module}'\nconsole.log(${name})\n`)) })

  const sections = [
    { group: 'published', items: await measurePublishedFiles() },
    { group: 'component', items: [] },
    { group: 'composable', items: [] },
    { group: 'core', items: [] },
  ]
  for (const name of components) sections[1].items.push(await consumer('vue-weave', name))
  for (const name of composables) sections[2].items.push(await consumer('vue-weave', name))
  for (const name of coreSamples.filter(sample => sample in core)) sections[3].items.push(await consumer('vue-weave/core', name))
  return toRows(sections)
}

function readArgs(argv) {
  const known = new Set(['--update', '--check'])
  const unknown = argv.filter(arg => !known.has(arg))
  if (unknown.length > 0) throw new Error(`Unknown argument ${unknown.join(', ')}. Use --update or --check.`)
  return { update: argv.includes('--update'), check: argv.includes('--check') }
}

async function main() {
  const { update, check } = readArgs(process.argv.slice(2))
  try { readFileSync(join(root, 'dist', 'index.js')) } catch { throw new Error('dist/ is missing. Run `npm run build` first.') }
  const rows = await measureAll()
  console.log(renderTable(rows))

  mkdirSync(resolve(outputPath, '..'), { recursive: true })
  writeFileSync(outputPath, JSON.stringify({ measuredAt: new Date().toISOString(), node: process.version, rows }, null, 2) + '\n')
  console.log(`\nWrote ${outputPath}`)

  if (update) {
    writeFileSync(baselinePath, JSON.stringify(toBaseline(rows), null, 2) + '\n')
    console.log(`Updated ${baselinePath}`)
  }
  if (check) {
    let baseline
    try { baseline = JSON.parse(readFileSync(baselinePath, 'utf8')) } catch {
      throw new Error('size-baseline.json is missing or unreadable. Create it with `npm run build && npm run size -- --update`.')
    }
    const result = compareToBaseline(rows, baseline)
    for (const note of result.notes) console.log(`note: ${note}`)
    if (!result.ok) {
      for (const problem of result.problems) console.error(`size: ${problem}`)
      console.error('\nIf the change is intended, refresh the baseline with `npm run build && npm run size -- --update` and commit size-baseline.json.')
      process.exitCode = 1
    } else {
      console.log('Sizes are within the baseline tolerance.')
    }
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main().catch(error => { console.error(error.message); process.exitCode = 1 })
}
